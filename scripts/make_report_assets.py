def read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path) as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k, v in r.items():
            try:
                r[k] = float(v) if k != "seed" else int(v)
            except (TypeError, ValueError):
                pass
    return rows


def index(rows: list[dict]) -> dict:
    out = defaultdict(dict)
    for r in rows:
        out[r["variant"]][(r["scene"], int(r["seed"]))] = r
    return out


class Macros:
    """Numbers quoted in the text, as LaTeX macros (digits spelt out: macro names cannot hold them)."""

    WORDS = dict(zip("0123456789", ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]))

    def __init__(self):
        self.lines = []

    def add(self, name: str, value: str) -> None:
        clean = "".join(self.WORDS.get(c, c) for c in name)
        clean = re.sub(r"[^A-Za-z]", "", clean)
        self.lines.append(f"\\newcommand{{\\{clean}}}{{{value}}}")

    def write(self, path: Path) -> None:
        path.write_text("% generated by scripts/make_report_assets.py\n" + "\n".join(self.lines) + "\n")


def fmt_p(p: float) -> str:
    if np.isnan(p):
        return "--"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def seed_stats(runs: dict, metric: str, scenes: list[str]) -> tuple[float, float, int]:
    """Mean and std over seeds of the scene-averaged metric (complete seeds only)."""
    seeds = sorted({s for _, s in runs})
    vals = [np.mean([runs[(sc, s)][metric] for sc in scenes]) for s in seeds if all((sc, s) in runs for sc in scenes)]
    if not vals:
        return float("nan"), float("nan"), 0
    return float(np.mean(vals)), float(np.std(vals, ddof=1)) if len(vals) > 1 else float("nan"), len(vals)


def paired(a: dict, b: dict, metric: str) -> dict:
    keys = sorted(set(a) & set(b))
    scenes = sorted({s for s, _ in keys})
    d = np.array([np.mean([a[k][metric] - b[k][metric] for k in keys if k[0] == s]) for s in scenes])
    higher = metric in ("psnr", "ssim", "delta1")
    p = float(stats.wilcoxon(d).pvalue) if len(d) >= 6 and np.any(d != 0) else float("nan")
    return {"diff": float(d.mean()) if len(d) else float("nan"), "p": p, "n": len(d),
            "wins": int(np.sum(d > 0) if higher else np.sum(d < 0)), "per_scene": dict(zip(scenes, d)),
            "seeds": len({s for _, s in keys})}


