def main_table(data: dict, macros: Macros) -> None:
    lines = [r"\begin{tabular}{@{}llcccc@{}}", r"\toprule",
             r" & Variant & PSNR$\uparrow$ & SSIM$\uparrow$ & LPIPS$\downarrow$ & AbsRel$\downarrow$ \\", r"\midrule"]
    for bench in BENCHES:
        runs, geo, scenes = data[bench["key"]]["runs"], data[bench["key"]]["geo"], data[bench["key"]]["scenes"]
        present = [v for v in VARIANTS if v in runs]
        best = {}
        for m in ("psnr", "ssim", "lpips"):
            vals = {v: seed_stats(runs[v], m, scenes)[0] for v in present}
            best[m] = (max if m != "lpips" else min)(vals, key=lambda v: vals[v] if not np.isnan(vals[v]) else
                                                         (-1e9 if m != "lpips" else 1e9))
        for i, v in enumerate(present):
            cells = []
            for m, digits in (("psnr", 2), ("ssim", 3), ("lpips", 3)):
                mean, sd, n = seed_stats(runs[v], m, scenes)
                text = f"{mean:.{digits}f}" if n else "--"
                if n > 1 and m == "psnr":
                    text += rf"\,$\pm$\,{sd:.{digits}f}"
                if v == best[m] and n:
                    text = rf"\textbf{{{text}}}"
                cells.append(text)
                if n:
                    macros.add(f"{bench['label']}{v}{m}", f"{mean:.{digits}f}")
                    macros.add(f"{bench['label']}{v}{m}seeds", str(n))
            g = [r["absrel"] for r in geo.get(v, {}).values()]
            cells.append(f"{np.mean(g):.3f}" if g else "--")
            if g:
                macros.add(f"{bench['label']}{v}absrel", f"{np.mean(g):.3f}")
            head = rf"\multirow{{{len(present)}}}{{*}}{{\rotatebox{{90}}{{{bench['label']}}}}}" if i == 0 else ""
            lines.append(f"{head} & {v} {SHORT_NAMES[v]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\midrule" if bench is not BENCHES[-1] else r"\bottomrule")
    lines.append(r"\end{tabular}")
    (GEN / "table_main.tex").write_text("\n".join(lines) + "\n")


def paired_table(data: dict, macros: Macros) -> None:
    lines = [r"\begin{tabular}{@{}llrrrr@{}}", r"\toprule",
             r" & Comparison & $\Delta$PSNR & $p$ & Wins & $\Delta$AbsRel \\", r"\midrule"]
    for bench in BENCHES:
        runs, geo = data[bench["key"]]["runs"], data[bench["key"]]["geo"]
        rows = [(a, b) for a, b in COMPARISONS if a in runs and b in runs]
        for i, (a, b) in enumerate(rows):
            p = paired(runs[a], runs[b], "psnr")
            g = paired(geo[a], geo[b], "absrel") if a in geo and b in geo else None
            tag = f"{bench['label']}{a}minus{b}"
            macros.add(tag + "dpsnr", f"{p['diff']:+.2f}")
            macros.add(tag + "p", fmt_p(p["p"]))
            macros.add(tag + "wins", f"{p['wins']}/{p['n']}")
            for m in ("ssim", "lpips"):
                q = paired(runs[a], runs[b], m)
                macros.add(tag + "d" + m, f"{q['diff']:+.4f}")
            if g:
                macros.add(tag + "dabsrel", f"{g['diff']:+.4f}")
                macros.add(tag + "absrelp", fmt_p(g["p"]))
                macros.add(tag + "absrelwins", f"{g['wins']}/{g['n']}")
            head = rf"\multirow{{{len(rows)}}}{{*}}{{\rotatebox{{90}}{{{bench['label']}}}}}" if i == 0 else ""
            lines.append(f"{head} & {a}$-${b} & {p['diff']:+.2f} & {fmt_p(p['p'])} & {p['wins']}/{p['n']} & "
                         + (f"{g['diff']:+.4f}" if g else "--") + r" \\")
        lines.append(r"\midrule" if bench is not BENCHES[-1] else r"\bottomrule")
    lines.append(r"\end{tabular}")
    (GEN / "table_paired.tex").write_text("\n".join(lines) + "\n")


CALIB_MACROS = {"ause": "ause", "aurg": "aurg", "aurg_depth": "aurgdepth", "spearman_conf_vs_error": "spearman",
                "partial_spearman": "partial", "spearman_conf_vs_depth": "confdepth",
                "mean_abs_rel_error": "meanrel"}


def calibration(data: dict, macros: Macros) -> dict:
    curves = {}
    lines = [r"\begin{tabular}{@{}lcccccc@{}}", r"\toprule",
             r" & AUSE$\downarrow$ & AURG$\uparrow$ & \makecell{AURG\\(depth)} & $\rho_s(c,e)$ & "
             r"\makecell{$\rho_s(c,e)$\\$|$depth} & $\rho_s(c,d)$ \\", r"\midrule"]
    for bench in BENCHES:
        files = sorted((REPO_ROOT / "results" / "calibration" / bench["key"]).glob("*.json"))
        if not files:
            continue
        res = [json.loads(f.read_text()) for f in files]
        views = [v for r in res for v in r["per_view"]]
        curves[bench["label"]] = {name: np.mean([v[key] for v in views], axis=0) for name, key in
                                  (("conf", "curve_confidence"), ("oracle", "curve_oracle"), ("depth", "curve_depth"))
                                  if all(key in v for v in views)}
        m = {k: float(np.mean([r["mean"][k] for r in res])) for k in CALIB_MACROS if all(k in r["mean"] for r in res)}
        lines.append(f"{bench['label']} ({len(res)}) & {m['ause']:.3f} & {m['aurg']:.3f} & {m.get('aurg_depth', np.nan):.3f} & "
                     f"{m['spearman_conf_vs_error']:+.2f} & {m.get('partial_spearman', np.nan):+.2f} & "
                     f"{m.get('spearman_conf_vs_depth', np.nan):+.2f} \\\\")
        for k, v in m.items():
            macros.add(f"{bench['label']}calib{CALIB_MACROS[k]}", f"{v:.3f}" if "spearman" not in k else f"{v:+.2f}")
        macros.add(f"{bench['label']}calibpositive", f"{sum(r['mean']['aurg'] > 0 for r in res)}/{len(res)}")
        if "aurg_depth" in m:
            macros.add(f"{bench['label']}calibbeyonddepth",
                       f"{sum(r['mean']['aurg'] > r['mean']['aurg_depth'] for r in res)}/{len(res)}")
        data[bench["key"]]["calib"] = {r["scene"]: r["mean"] for r in res}
    lines += [r"\bottomrule", r"\end{tabular}"]
    (GEN / "table_calibration.tex").write_text("\n".join(lines) + "\n")
    return curves


def weight_by_depth(macros: Macros) -> None:
    """How V2's rank weights split between the nearest and farthest third of each prior depth map."""
    from scipy.stats import rankdata
    for bench in BENCHES:
        cfg = yaml.safe_load((REPO_ROOT / bench["config"]).read_text())
        near, far, rho = [], [], []
        for f in sorted((REPO_ROOT / cfg["prior_root"]).glob("*/*.npz")):
            with np.load(f) as z:
                d, c = z["depth"].ravel(), z["conf"].ravel()
            w = (rankdata(c) - 1) / (c.size - 1)
            lo, hi = np.quantile(d, [1 / 3, 2 / 3])
            near.append(w[d <= lo].mean())
            far.append(w[d >= hi].mean())
            rho.append(stats.spearmanr(c, d).statistic)
        if near:
            macros.add(f"{bench['label']}weightnear", f"{np.mean(near):.2f}")
            macros.add(f"{bench['label']}weightfar", f"{np.mean(far):.2f}")
            macros.add(f"{bench['label']}confdepthall", f"{np.mean(rho):+.2f}")


