def fig_sparsification(curves: dict) -> None:
    if not curves:
        return
    fig, axes = plt.subplots(1, len(curves), figsize=(3.45, 2.0), sharey=True)
    axes = np.atleast_1d(axes)
    x = np.linspace(0, 99, 100)
    for ax, (label, c) in zip(axes, curves.items()):
        ax.axhline(1.0, color=COLOURS["V0"], lw=1.2, ls=(0, (3, 2)), label="Random")
        if "depth" in c:
            ax.plot(x, c["depth"], color=COLOURS["V3"], lw=1.3, label="By depth (far first)")
        ax.plot(x, c["conf"], color=COLOURS["V1"], lw=1.6, label="By confidence")
        ax.plot(x, c["oracle"], color=COLOURS["V2"], lw=1.6, label="Oracle")
        ax.fill_between(x, c["oracle"], c["conf"], color=COLOURS["V1"], alpha=0.10, lw=0)
        ax.set_title(label, color=INK)
        ax.set_xlabel("Pixels removed (%)")
        ax.set_xlim(0, 99)
        ax.set_ylim(0, 1.4)
    axes[0].set_ylabel("Relative depth error\nof remaining pixels")
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncol=2, fontsize=6.5, handlelength=1.6,
               bbox_to_anchor=(0.5, 1.0), columnspacing=1.0)
    fig.tight_layout(pad=0.3, w_pad=0.6, rect=(0, 0, 1, 0.80))
    fig.savefig(FIG / "sparsification.pdf")
    plt.close(fig)


def fig_per_scene(data: dict) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(7.1, 2.2), gridspec_kw={"width_ratios": [8, 17]}, sharey=True)
    for ax, bench in zip(axes, BENCHES):
        runs = data[bench["key"]]["runs"]
        shown = [v for v in ("V1", "V2", "V4") if v in runs]
        if "V0" not in runs or not shown:
            continue
        gains = {v: paired(runs[v], runs["V0"], "psnr")["per_scene"] for v in shown}
        scenes = sorted(set.intersection(*(set(g) for g in gains.values())))
        xs = np.arange(len(scenes))
        ax.axhline(0, color=MUTED, lw=0.8)
        width = 0.8 / len(shown)
        for i, v in enumerate(shown):
            ax.bar(xs + (i - (len(shown) - 1) / 2) * width, [gains[v][s] for s in scenes], width * 0.92,
                   color=COLOURS[v], label=f"{v}: {VARIANT_NAMES[v]}")
        if len(scenes) < 10:
            ax.set_xticks(xs, scenes, rotation=35, ha="right", rotation_mode="anchor", fontsize=6.5)
        else:
            ax.set_xticks(xs, [s.replace("statue", "") for s in scenes], fontsize=6.5)
            ax.set_xlabel("Statue", fontsize=6.5)
        ax.set_title(f"{bench['label']} ({bench['views']} views)", color=INK)
        ax.grid(axis="x", visible=False)
    axes[0].set_ylabel(r"$\Delta$PSNR vs. V0 (dB)")
    handles, labels = axes[0].get_legend_handles_labels()
    if handles:
        fig.legend(handles, labels, loc="upper center", ncol=len(handles), fontsize=6.5, bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout(pad=0.3, w_pad=0.8, rect=(0, 0, 1, 0.9))
    fig.savefig(FIG / "per_scene.pdf")
    plt.close(fig)


def fig_sensitivity(data: dict, macros: Macros) -> None:
    runs = data["llff3"]["runs"]
    scenes = ["fern", "horns"]
    weights = {0.05: (runs, None)}
    for d in sorted(REPO_ROOT.glob("outputs/llff3-w*")):
        w = float(d.name.split("-w")[1])
        weights[w] = (None, d)
    table = defaultdict(dict)  # variant -> weight -> mean PSNR over the two scenes (seed 0)
    for w, (rs, d) in weights.items():
        for v in ("V1", "V2"):
            vals = []
            for s in scenes:
                if rs is not None:
                    r = rs.get(v, {}).get((s, 0))
                    vals.append(r["psnr"] if r else np.nan)
                else:
                    f = d / v / s / "seed0" / "metrics.json"
                    vals.append(json.loads(f.read_text())["mean"]["psnr"] if f.exists() else np.nan)
            if not np.isnan(vals).any():
                table[v][w] = float(np.mean(vals))
    if len(table.get("V1", {})) < 2:
        return
    base = np.mean([runs["V0"][(s, 0)]["psnr"] for s in scenes])
    fig, ax = plt.subplots(figsize=(3.45, 1.6))
    ax.axhline(base, color=COLOURS["V0"], lw=1.2, ls=(0, (3, 2)), label="Baseline (no depth)")
    for v in ("V1", "V2"):
        ws = sorted(table[v])
        ax.plot(ws, [table[v][w] for w in ws], color=COLOURS[v], lw=1.6, marker="o", ms=3.5, label=VARIANT_NAMES[v])
    ax.set_xscale("log")
    ax.set_xticks(sorted(weights), [f"{w:g}" for w in sorted(weights)])
    ax.minorticks_off()
    ax.set_xlabel(r"Depth-loss weight $\lambda_d$")
    ax.set_ylabel("PSNR (dB), fern+horns")
    ax.legend(fontsize=6.5, loc="lower center")
    fig.tight_layout(pad=0.3)
    fig.savefig(FIG / "sensitivity.pdf")
    plt.close(fig)
    best = max(table["V1"], key=table["V1"].get)
    macros.add("sensbestweight", f"{best:g}")
    lines = [r"\begin{tabular}{@{}l" + "c" * len(table["V1"]) + "@{}}", r"\toprule",
             r"$\lambda_d$ & " + " & ".join(f"{w:g}" for w in sorted(table["V1"])) + r" \\", r"\midrule"]
    for v in ("V1", "V2"):
        lines.append(f"{v} & " + " & ".join(f"{table[v].get(w, float('nan')):.2f}" for w in sorted(table["V1"])) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (GEN / "table_sensitivity.tex").write_text("\n".join(lines) + "\n")


def crop_and_label(img: np.ndarray, text: str) -> np.ndarray:
    img = img.copy()
    scale = img.shape[1] / 420
    thick = max(1, round(scale * 1.6))
    (tw, th), _ = cv2.getTextSize(text, cv2.FONT_HERSHEY_SIMPLEX, 0.5 * scale, thick)
    cv2.rectangle(img, (0, img.shape[0] - th - int(12 * scale)), (tw + int(10 * scale), img.shape[0]), (0, 0, 0), -1)
    cv2.putText(img, text, (int(5 * scale), img.shape[0] - int(6 * scale)), cv2.FONT_HERSHEY_SIMPLEX,
                0.5 * scale, (255, 255, 255), thick, cv2.LINE_AA)
    return img


def fig_qualitative(data: dict, macros: Macros) -> None:
    """Rows: for each benchmark, the scene with the largest and the smallest V1-V0 gain (seed 0)."""
    rows = []
    captions = []
    for bench in BENCHES:
        runs = data[bench["key"]]["runs"]
        if not all(v in runs for v in ("V0", "V1", "V2")):
            continue
        d = paired(runs["V1"], runs["V0"], "psnr")["per_scene"]
        ordered = sorted(d, key=d.get)
        for scene, kind in ((ordered[-1], "largest gain"), (ordered[0], "smallest gain")):
            metrics = {v: json.loads((REPO_ROOT / "outputs" / bench["key"] / v / scene / "seed0" /
                                      "metrics.json").read_text())["per_image"] for v in ("V0", "V1", "V2")}
            gains = [b["psnr"] - a["psnr"] for a, b in zip(metrics["V0"], metrics["V1"])]
            view = int(np.argmax(gains)) if kind == "largest gain" else int(np.argmin(gains))
            tiles = []
            base = REPO_ROOT / "outputs" / bench["key"]
            gt = cv2.imread(str(base / "V0" / scene / "seed0" / "test" / "ours_10000" / "gt" / f"{view:05d}.png"))
            tiles.append(crop_and_label(gt, f"GT  {scene}"))
            for v in ("V0", "V1", "V2"):
                img = cv2.imread(str(base / v / scene / "seed0" / "test" / "ours_10000" / "renders" / f"{view:05d}.png"))
                tiles.append(crop_and_label(img, f"{v}  {metrics[v][view]['psnr']:.2f} dB"))
            h = 300
            tiles = [cv2.resize(t, (round(t.shape[1] * h / t.shape[0]), h), interpolation=cv2.INTER_AREA) for t in tiles]
            rows.append(np.hstack([np.pad(t, ((2, 2), (2, 2), (0, 0)), constant_values=255) for t in tiles]))
            captions.append(f"{bench['label']} {scene} ({kind})")
    if not rows:
        return
    width = max(r.shape[1] for r in rows)
    rows = [np.pad(r, ((0, 0), (0, width - r.shape[1]), (0, 0)), constant_values=255) for r in rows]
    cv2.imwrite(str(FIG / "qualitative.jpg"), np.vstack(rows), [cv2.IMWRITE_JPEG_QUALITY, 92])
    macros.add("qualrows", "; ".join(captions))


def fig_dataset() -> None:
    root = REPO_ROOT / "data" / "statues"
    scenes = sorted(p for p in root.glob("statue*") if (p / "prep.json").exists())
    if not scenes:
        return
    tiles = []
    for s in scenes:
        prep = json.loads((s / "prep.json").read_text())
        img = cv2.imread(str(s / "images" / f"{prep['train_views'][0]}.jpg"))
        img = cv2.resize(img, (216, 384), interpolation=cv2.INTER_AREA)
        tiles.append(crop_and_label(img, s.name.replace("statue", "S")))
    per_row = (len(tiles) + 1) // 2
    blank = np.full_like(tiles[0], 255)
    tiles += [blank] * (2 * per_row - len(tiles))
    grid = np.vstack([np.hstack([np.pad(t, ((2, 2), (2, 2), (0, 0)), constant_values=255) for t in tiles[i:i + per_row]])
                      for i in (0, per_row)])
    cv2.imwrite(str(FIG / "statues_dataset.jpg"), grid, [cv2.IMWRITE_JPEG_QUALITY, 90])


