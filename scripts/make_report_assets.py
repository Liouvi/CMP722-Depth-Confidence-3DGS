def fig_prior(macros: Macros) -> None:
    """Training view, prior depth, confidence and prior error, one LLFF and one statue view."""
    import torch
    sys.path.insert(0, str(REPO_ROOT / "third_party" / "DropGaussian"))
    from argparse import Namespace
    from scene import GaussianModel, Scene
    from cwdepth.calib.sparsification import MIN_ALPHA, align_scale_shift
    from cwdepth.priors.io import load_prior
    from cwdepth.render import render_with_depth

    picks = [("llff3", "configs/llff3.yaml", "llff-ref", "horns"),
             ("statues12", "configs/statues12.yaml", "statues-ref", "statue05")]
    fig, axes = plt.subplots(len(picks), 4, figsize=(7.1, 2.9), gridspec_kw={"wspace": 0.04, "hspace": 0.1})
    for row, (bench, cfg_path, ref, scene_name) in enumerate(picks):
        cfg = yaml.safe_load((REPO_ROOT / cfg_path).read_text())
        ref_run = REPO_ROOT / "outputs" / ref / "V0" / scene_name / "seed0"
        if not (ref_run / "metrics.json").exists():
            continue
        scene_args = Namespace(source_path=str(REPO_ROOT / cfg["data_root"] / scene_name), model_path=str(ref_run),
                               images="images", resolution=cfg["train_args"]["resolution"], white_background=False,
                               data_device="cuda", eval=True, n_views=cfg["train_args"]["n_views"], rand_pcd=False,
                               sh_degree=3)
        g = GaussianModel(3)
        sc = Scene(scene_args, g, load_iteration=10000, shuffle=False)
        cam = sorted(sc.getTrainCameras(), key=lambda c: c.image_name)[1]
        pipe = Namespace(convert_SHs_python=False, compute_cov3D_python=False, debug=False)
        with torch.no_grad():
            out = render_with_depth(cam, g, pipe, torch.zeros(3, device="cuda"))
            valid = out["alpha"] > MIN_ALPHA
            ref_depth = out["depth"] / out["alpha"].clamp_min(1e-6)
            prior, conf = load_prior(REPO_ROOT / cfg["prior_root"] / scene_name, cam.image_name,
                                     cam.image_height, cam.image_width)
            aligned = torch.zeros_like(prior)
            aligned[valid] = align_scale_shift(prior[valid], ref_depth[valid])
            err = ((aligned - ref_depth).abs() / ref_depth.clamp_min(1e-6))
            err[~valid] = float("nan")
        image = cam.original_image.permute(1, 2, 0).cpu().numpy()
        panels = [(image, None, "Training view"), (1.0 / prior.cpu().numpy(), "inferno", "DA3 depth (inverse)"),
                  (conf.cpu().numpy(), "viridis", "DA3 confidence"),
                  (err.cpu().numpy(), "magma", "Prior error vs. reference")]
        for col, (arr, cmap, title) in enumerate(panels):
            ax = axes[row, col]
            if cmap is None:
                ax.imshow(arr)
            elif col == 3:
                ax.imshow(arr, cmap=cmap, vmin=0, vmax=np.nanpercentile(arr, 95))
            else:
                ax.imshow(arr, cmap=cmap, vmin=np.percentile(arr, 2), vmax=np.percentile(arr, 98))
            ax.set_xticks([])
            ax.set_yticks([])
            ax.grid(False)
            for sp in ax.spines.values():
                sp.set_visible(False)
            if row == 0:
                ax.set_title(title, color=INK)
        axes[row, 0].set_ylabel(f"{scene_name}", color=INK)
        del sc, g
        torch.cuda.empty_cache()
    fig.savefig(FIG / "prior_error.pdf", bbox_inches="tight", pad_inches=0.02)
    plt.close(fig)


